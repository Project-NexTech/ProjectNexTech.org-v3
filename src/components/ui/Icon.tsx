export type IconName = keyof typeof STROKE_ICONS | keyof typeof BRAND_ICONS

export interface IconProps {
  name: IconName | (string & {})
  size?: number
  className?: string
  /** Supplying a title makes the icon a labelled image instead of decoration. */
  title?: string
}

export default function Icon({ name, size = 20, className = '', title }: IconProps) {
  const brand = BRAND_ICONS[name as keyof typeof BRAND_ICONS]
  const stroke = STROKE_ICONS[name as keyof typeof STROKE_ICONS]

  if (!brand && !stroke) {
    /* Vite exposed this as import.meta.env.DEV; under Next it is NODE_ENV,
       which the bundler statically replaces so the branch is dropped from the
       production build. */
    if (process.env.NODE_ENV !== 'production') {
      console.warn(`[Icon] unknown icon "${name}"`)
    }
    return null
  }

  const shared = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    className,
    'aria-hidden': title ? undefined : true,
    role: title ? 'img' : 'presentation',
    focusable: 'false' as const,
  }

  if (brand) {
    return (
      <svg {...shared} fill="currentColor">
        {title && <title>{title}</title>}
        <path d={brand} />
      </svg>
    )
  }

  return (
    <svg
      {...shared}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      {title && <title>{title}</title>}
      <path d={stroke} />
    </svg>
  )
}
